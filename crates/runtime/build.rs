//! Build script of `uncharted_runtime` (piece 3.01):
//!
//! - the NID table: `src/import_names.inc` (written by `tools/import_names.py`) becomes
//!   `$OUT_DIR/nid_table.rs`, sorted by NID so `abi::nid_name` can bisect;
//! - `cfg(uncharted_loader)`: set when `UNCHARTED_RUNTIME_LOADER=1`, for the static library that
//!   is linked into the C loader. Only then does the Rust side call the C modules that are still
//!   C (their resolvers and reports, `runtime_quit`); `cargo test` and the mobile builds link
//!   no C;
//! - the GPU library: with `UNCHARTED_GPU_BUILD=<build dir>`, CMake and Ninja build `gpu/` (the
//!   `bbgpu` target) there before the crate is compiled. `build.sh` sets it on Linux; on Windows
//!   CMake builds `gpu/` and the loader and runs cargo itself, so this step is not used there.
//!   Apple targets (macOS, iOS) never build `gpu/`: CI leaves the variable unset and this script
//!   refuses it for them (8.02; the Apple renderer is Metal, 8.04);
//! - the Windows link flags of `uncharted-run`: no high-entropy ASLR and a 16 MiB committed main
//!   stack, as `gpu/CMakeLists.txt` gives `bb-probe` (see `windows_bin_link_args`).

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

fn main() {
    let manifest =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let root = manifest.join("../..");
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    nid_table(&root, &out);
    loader_cfg();
    windows_bin_link_args();
    gpu(&root);
}

/// `uncharted-run` reserves the PS4 address range (64 GiB - 1 TiB) at boot (`memory/windows.rs`).
/// With high-entropy ASLR, Windows may put heaps, thread stacks or mapped files inside it, and
/// the reservation then fails with exit 21. Link the runner the way `gpu/CMakeLists.txt` links
/// `bb-probe`: `--disable-high-entropy-va` keeps those allocations low, and the main stack is
/// 16 MiB reserved and committed. Only the binary: the library is linked into other programs.
fn windows_bin_link_args() {
    if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }
    let args: &[&str] = if env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        &["/HIGHENTROPYVA:NO", "/STACK:16777216,16777216"]
    } else {
        // `-Wl,` would split `16777216,16777216` at the comma; `-Xlinker` passes it whole.
        &[
            "-Wl,--disable-high-entropy-va",
            "-Xlinker",
            "--stack",
            "-Xlinker",
            "16777216,16777216",
        ]
    };
    for arg in args {
        println!("cargo::rustc-link-arg-bin=uncharted-run={arg}");
    }
}

/// Every `{"nid","symbol"},` line of `import_names.inc`, sorted by NID (bytewise, as `strcmp`).
/// Other lines are comments. A duplicate NID stops the build: the C table answered with its
/// first match, a sorted table could not tell which one was meant.
fn nid_table(root: &Path, out: &Path) {
    let source = root.join("src/import_names.inc");
    println!("cargo::rerun-if-changed={}", source.display());
    let text = fs::read_to_string(&source).unwrap_or_else(|e| panic!("{}: {e}", source.display()));
    let mut entries = Vec::new();
    for (number, line) in text.lines().enumerate() {
        let line = line.trim();
        if !line.starts_with('{') {
            continue;
        }
        let pair = line
            .strip_prefix("{\"")
            .and_then(|rest| rest.strip_suffix("\"},"))
            .and_then(|inner| inner.split_once("\",\""))
            .filter(|(nid, symbol)| !nid.contains('"') && !symbol.contains('"'));
        let Some((nid, symbol)) = pair else {
            panic!(
                "{}:{}: not a {{\"nid\",\"symbol\"}}, line",
                source.display(),
                number + 1
            );
        };
        entries.push((nid.to_owned(), symbol.to_owned()));
    }
    entries.sort();
    if let Some(pair) = entries.windows(2).find(|pair| pair[0].0 == pair[1].0) {
        panic!("{}: NID {} is listed twice", source.display(), pair[0].0);
    }
    let mut table = String::from(
        "// Generated by build.rs from src/import_names.inc.\n\
         /// NID to symbol name for eboot and linked libc imports (diagnostics only): the C\n\
         /// `import_names.inc`, `(c\"bzQExy189ZI#q#q\", c\"_init_env\")` and so on, sorted by NID\n\
         /// (bytewise, as `strcmp`) so a lookup can bisect.\n\
         pub static NID_TABLE: &[(&CStr, &CStr)] = &[\n",
    );
    for (nid, symbol) in &entries {
        writeln!(table, "    (c{nid:?}, c{symbol:?}),").unwrap();
    }
    table.push_str("];\n");
    fs::write(out.join("nid_table.rs"), table).expect("write nid_table.rs");
}

fn loader_cfg() {
    println!("cargo::rustc-check-cfg=cfg(uncharted_loader)");
    println!("cargo::rustc-check-cfg=cfg(uncharted_gpu)");
    println!("cargo::rerun-if-env-changed=UNCHARTED_RUNTIME_LOADER");
    if env::var("UNCHARTED_RUNTIME_LOADER").as_deref() == Ok("1") {
        println!("cargo::rustc-cfg=uncharted_loader");
    }
}

/// `cmake -S gpu -B <dir> -G Ninja <args>` then `ninja -C <dir> bbgpu`, as `build.sh` did. The
/// CMake arguments come in `UNCHARTED_GPU_CMAKE_ARGS`, separated by the unit separator (0x1f),
/// so a value can hold spaces. Ninja's output goes to `UNCHARTED_GPU_LOG` (default
/// `<dir>/gpu-build.log`); a failure prints the last 40 lines that are not progress lines and
/// stops the build, so an older library is never used silently.
fn gpu(root: &Path) {
    for name in [
        "UNCHARTED_GPU_BUILD",
        "UNCHARTED_GPU_CMAKE_ARGS",
        "UNCHARTED_GPU_LOG",
        "BB_JOBS",
    ] {
        println!("cargo::rerun-if-env-changed={name}");
    }
    let Some(dir) = env::var_os("UNCHARTED_GPU_BUILD").map(PathBuf::from) else {
        return;
    };
    // gpu/ needs X11 and a Vulkan loader, which Apple targets do not have. On Apple the renderer
    // is Metal (8.04), so a request to build gpu/ there is an error, not a silent skip.
    if env::var("CARGO_CFG_TARGET_VENDOR").as_deref() == Ok("apple") {
        panic!(
            "UNCHARTED_GPU_BUILD is set for an Apple target: gpu/ is not built there (8.04 Metal)"
        );
    }
    let gpu = root.join("gpu");
    // The sources, and the library itself (a deleted build directory builds again). Ninja does
    // not touch an up-to-date library, so this does not rerun on every build.
    println!("cargo::rerun-if-changed={}", gpu.display());
    let library = if cfg!(windows) {
        "libbbgpu.a"
    } else {
        "libbbgpu.so"
    };
    println!("cargo::rerun-if-changed={}", dir.join(library).display());
    let log =
        env::var_os("UNCHARTED_GPU_LOG").map_or_else(|| dir.join("gpu-build.log"), PathBuf::from);
    let mut cmake = Command::new("cmake");
    cmake
        .arg("-S")
        .arg(&gpu)
        .arg("-B")
        .arg(&dir)
        .args(["-G", "Ninja"]);
    if let Ok(args) = env::var("UNCHARTED_GPU_CMAKE_ARGS") {
        cmake.args(args.split('\u{1f}').filter(|arg| !arg.is_empty()));
    }
    run(cmake.stdout(Stdio::null()), "cmake (gpu/)", None);
    let mut ninja = Command::new("ninja");
    if let Ok(jobs) = env::var("BB_JOBS") {
        if !jobs.is_empty() {
            ninja.arg(format!("-j{jobs}"));
        }
    }
    ninja.arg("-C").arg(&dir).arg("bbgpu");
    run(&mut ninja, "GPU library build", Some(&log));

    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux") {
        let out = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
        build_atrac9(root, &out);
        println!("cargo::rustc-cfg=uncharted_gpu");
        println!("cargo::rustc-link-search=native={}", dir.display());
        println!("cargo::rustc-link-search=native={}", out.display());
        println!("cargo::rustc-link-lib=dylib=bbgpu");
        println!("cargo::rustc-link-lib=static=atrac9");
        println!("cargo::rustc-link-lib=dylib=SDL3");
        println!("cargo::rustc-link-arg-bin=uncharted-run=-rdynamic");
        println!("cargo::rustc-link-arg-bin=uncharted-run=-Wl,-rpath,$ORIGIN/gpu");
        println!("cargo::rustc-link-arg-bin=uncharted-run=-Wl,-rpath,$ORIGIN");
        println!(
            "cargo::rustc-link-arg-bin=uncharted-run=-Wl,-rpath,{}",
            dir.display()
        );
        for sym in [
            "runtime_map_guest_memory",
            "runtime_memory_set_gpu_hooks",
            "runtime_memory_write_backing",
            "runtime_memory_read_backing",
            "runtime_memory_clamp",
            "runtime_memory_region",
            "runtime_memory_gpu_protect",
            "runtime_memory_is_mapped",
            "runtime_disabled_optimizations",
            "runtime_disabled_optimizations2",
            "runtime_benchmark_active",
            "runtime_benchmark_frame",
            "runtime_errno",
            "runtime_file_translate",
            "runtime_process_time_counter",
            "runtime_process_time_us",
            "runtime_savedata_wait_idle",
            "runtime_thread_attach_host",
            "runtime_thread_join_spawned",
            "runtime_thread_spawn",
            "runtime_tsc_frequency",
        ] {
            println!("cargo::rustc-link-arg-bin=uncharted-run=-Wl,--undefined={sym}");
        }
    }
}

fn build_atrac9(root: &Path, out: &Path) {
    let src_dir = root.join("third_party/LibAtrac9/C/src");
    let lib = out.join("libatrac9.a");
    let obj_dir = out.join("atrac9");
    fs::create_dir_all(&obj_dir).expect("create atrac9 object dir");
    let cc = env::var("CC").unwrap_or_else(|_| "cc".to_owned());
    let ar = env::var("AR").unwrap_or_else(|_| "ar".to_owned());
    let mut objs = Vec::new();
    let entries = fs::read_dir(&src_dir).unwrap_or_else(|e| panic!("{}: {e}", src_dir.display()));
    for entry in entries.flatten() {
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) != Some("c") {
            continue;
        }
        println!("cargo::rerun-if-changed={}", path.display());
        let obj = obj_dir.join(format!(
            "{}.o",
            path.file_stem().expect("c stem").to_string_lossy()
        ));
        let mut cmd = Command::new(&cc);
        cmd.args(["-std=c99", "-O2", "-g", "-w", "-c"])
            .arg(&path)
            .arg("-o")
            .arg(&obj);
        run(&mut cmd, "atrac9 compile", None);
        objs.push(obj);
    }
    objs.sort();
    let _ = fs::remove_file(&lib);
    let mut cmd = Command::new(&ar);
    cmd.arg("rcs").arg(&lib).args(&objs);
    run(&mut cmd, "atrac9 archive", None);
}

fn run(command: &mut Command, what: &str, log: Option<&Path>) {
    let output = command.stderr(Stdio::piped());
    let output = if log.is_some() {
        output.stdout(Stdio::piped())
    } else {
        output
    };
    let result = output
        .output()
        .unwrap_or_else(|e| panic!("{what}: cannot start: {e}"));
    let mut text = result.stdout;
    text.extend_from_slice(&result.stderr);
    if let Some(log) = log {
        fs::write(log, &text).unwrap_or_else(|e| panic!("{}: {e}", log.display()));
    }
    if result.status.success() {
        return;
    }
    let text = String::from_utf8_lossy(&text);
    let lines: Vec<&str> = text.lines().filter(|line| !line.starts_with('[')).collect();
    for line in &lines[lines.len().saturating_sub(40)..] {
        eprintln!("{line}");
    }
    match log {
        Some(log) => panic!("{what} failed (full log: {})", log.display()),
        None => panic!("{what} failed ({})", result.status),
    }
}
