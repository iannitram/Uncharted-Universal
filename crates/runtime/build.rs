//! Build script of `uncharted_runtime` (piece 3.01):
//!
//! - the NID table: `src/import_names.inc` (written by `tools/import_names.py`) becomes
//!   `$OUT_DIR/nid_table.rs`, sorted by NID so `abi::nid_name` can bisect;
//! - `cfg(uncharted_loader)`: set when `UNCHARTED_RUNTIME_LOADER=1`, for the static library that
//!   is linked into the C loader. Only then does the Rust side call the C modules that are still
//!   C (their resolvers and reports, `runtime_quit`); `cargo test` and the mobile builds link
//!   no C;
//! - the GPU library: with `UNCHARTED_GPU_BUILD=<build dir>`, CMake and Ninja build `gpu/` (the
//!   `bbgpu` target) there before the crate is compiled. `build.sh` sets it on Linux; on Windows
//!   CMake builds `gpu/` and the loader and runs cargo itself, so this step is not used there.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

fn main() {
    let manifest =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let root = manifest.join("../..");
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    nid_table(&root, &out);
    loader_cfg();
    gpu(&root);
}

/// Every `{"nid","symbol"},` line of `import_names.inc`, sorted by NID (bytewise, as `strcmp`).
/// Other lines are comments. A duplicate NID stops the build: the C table answered with its
/// first match, a sorted table could not tell which one was meant.
fn nid_table(root: &Path, out: &Path) {
    let source = root.join("src/import_names.inc");
    println!("cargo::rerun-if-changed={}", source.display());
    let text = fs::read_to_string(&source).unwrap_or_else(|e| panic!("{}: {e}", source.display()));
    let mut entries = Vec::new();
    for (number, line) in text.lines().enumerate() {
        let line = line.trim();
        if !line.starts_with('{') {
            continue;
        }
        let pair = line
            .strip_prefix("{\"")
            .and_then(|rest| rest.strip_suffix("\"},"))
            .and_then(|inner| inner.split_once("\",\""))
            .filter(|(nid, symbol)| !nid.contains('"') && !symbol.contains('"'));
        let Some((nid, symbol)) = pair else {
            panic!(
                "{}:{}: not a {{\"nid\",\"symbol\"}}, line",
                source.display(),
                number + 1
            );
        };
        entries.push((nid.to_owned(), symbol.to_owned()));
    }
    entries.sort();
    if let Some(pair) = entries.windows(2).find(|pair| pair[0].0 == pair[1].0) {
        panic!("{}: NID {} is listed twice", source.display(), pair[0].0);
    }
    let mut table = String::from(
        "// Generated by build.rs from src/import_names.inc.\n\
         /// NID to symbol name for eboot and linked libc imports (diagnostics only): the C\n\
         /// `import_names.inc`, `(c\"bzQExy189ZI#q#q\", c\"_init_env\")` and so on, sorted by NID\n\
         /// (bytewise, as `strcmp`) so a lookup can bisect.\n\
         pub static NID_TABLE: &[(&CStr, &CStr)] = &[\n",
    );
    for (nid, symbol) in &entries {
        writeln!(table, "    (c{nid:?}, c{symbol:?}),").unwrap();
    }
    table.push_str("];\n");
    fs::write(out.join("nid_table.rs"), table).expect("write nid_table.rs");
}

fn loader_cfg() {
    println!("cargo::rustc-check-cfg=cfg(uncharted_loader)");
    println!("cargo::rerun-if-env-changed=UNCHARTED_RUNTIME_LOADER");
    if env::var("UNCHARTED_RUNTIME_LOADER").as_deref() == Ok("1") {
        println!("cargo::rustc-cfg=uncharted_loader");
    }
}

/// `cmake -S gpu -B <dir> -G Ninja <args>` then `ninja -C <dir> bbgpu`, as `build.sh` did. The
/// CMake arguments come in `UNCHARTED_GPU_CMAKE_ARGS`, separated by the unit separator (0x1f),
/// so a value can hold spaces. Ninja's output goes to `UNCHARTED_GPU_LOG` (default
/// `<dir>/gpu-build.log`); a failure prints the last 40 lines that are not progress lines and
/// stops the build, so an older library is never used silently.
fn gpu(root: &Path) {
    for name in [
        "UNCHARTED_GPU_BUILD",
        "UNCHARTED_GPU_CMAKE_ARGS",
        "UNCHARTED_GPU_LOG",
        "BB_JOBS",
    ] {
        println!("cargo::rerun-if-env-changed={name}");
    }
    let Some(dir) = env::var_os("UNCHARTED_GPU_BUILD").map(PathBuf::from) else {
        return;
    };
    let gpu = root.join("gpu");
    // The sources, and the library itself (a deleted build directory builds again). Ninja does
    // not touch an up-to-date library, so this does not rerun on every build.
    println!("cargo::rerun-if-changed={}", gpu.display());
    let library = if cfg!(windows) {
        "libbbgpu.a"
    } else {
        "libbbgpu.so"
    };
    println!("cargo::rerun-if-changed={}", dir.join(library).display());
    let log =
        env::var_os("UNCHARTED_GPU_LOG").map_or_else(|| dir.join("gpu-build.log"), PathBuf::from);
    let mut cmake = Command::new("cmake");
    cmake
        .arg("-S")
        .arg(&gpu)
        .arg("-B")
        .arg(&dir)
        .args(["-G", "Ninja"]);
    if let Ok(args) = env::var("UNCHARTED_GPU_CMAKE_ARGS") {
        cmake.args(args.split('\u{1f}').filter(|arg| !arg.is_empty()));
    }
    run(cmake.stdout(Stdio::null()), "cmake (gpu/)", None);
    let mut ninja = Command::new("ninja");
    if let Ok(jobs) = env::var("BB_JOBS") {
        if !jobs.is_empty() {
            ninja.arg(format!("-j{jobs}"));
        }
    }
    ninja.arg("-C").arg(&dir).arg("bbgpu");
    run(&mut ninja, "GPU library build", Some(&log));
}

fn run(command: &mut Command, what: &str, log: Option<&Path>) {
    let output = command.stderr(Stdio::piped());
    let output = if log.is_some() {
        output.stdout(Stdio::piped())
    } else {
        output
    };
    let result = output
        .output()
        .unwrap_or_else(|e| panic!("{what}: cannot start: {e}"));
    let mut text = result.stdout;
    text.extend_from_slice(&result.stderr);
    if let Some(log) = log {
        fs::write(log, &text).unwrap_or_else(|e| panic!("{}: {e}", log.display()));
    }
    if result.status.success() {
        return;
    }
    let text = String::from_utf8_lossy(&text);
    let lines: Vec<&str> = text.lines().filter(|line| !line.starts_with('[')).collect();
    for line in &lines[lines.len().saturating_sub(40)..] {
        eprintln!("{line}");
    }
    match log {
        Some(log) => panic!("{what} failed (full log: {})", log.display()),
        None => panic!("{what} failed ({})", result.status),
    }
}
